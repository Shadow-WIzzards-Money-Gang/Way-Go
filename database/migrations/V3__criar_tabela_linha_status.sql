-- =====================================================================
-- Cria a tabela LINHA_STATUS (status operacional das linhas de transporte)
-- =====================================================================

CREATE TABLE LINHA_STATUS (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_LINHA      NUMBER          NOT NULL,
    STATUS        VARCHAR2(50)    NOT NULL,
    DESCRICAO     VARCHAR2(255),
    ORIGEM        VARCHAR2(30)    NOT NULL,
    ATUALIZADO_EM TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LINHA_STATUS PRIMARY KEY (ID),
    CONSTRAINT FK_LS_LINHA FOREIGN KEY (ID_LINHA)
        REFERENCES LINHA_TRANSPORTE (ID),
);

CREATE INDEX IDX_LS_LINHA_ATUALIZADO ON LINHA_STATUS (ID_LINHA, ATUALIZADO_EM);