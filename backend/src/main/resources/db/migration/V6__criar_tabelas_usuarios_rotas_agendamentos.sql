-- ============================================
-- 1. TABELA: USUARIO
-- Armazena os usuários cadastrados no WayGo.
-- ============================================

CREATE TABLE USUARIO (
    ID VARCHAR2(36) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL,
    SENHA_HASH VARCHAR2(255) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIO
        PRIMARY KEY (ID)
);

-- E-mail único sem diferenciar maiúsculas de minúsculas
-- (impede "Joao@x.com" e "joao@x.com" como contas distintas).
CREATE UNIQUE INDEX UK_USUARIO_EMAIL
    ON USUARIO (LOWER(EMAIL));


-- ============================================
-- 2. TABELA: ROLE
-- Armazena as roles disponíveis no sistema.
-- ============================================

CREATE TABLE ROLE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(30) NOT NULL,

    CONSTRAINT PK_ROLE
        PRIMARY KEY (ID),

    CONSTRAINT UK_ROLE_NOME
        UNIQUE (NOME)
);


-- ============================================
-- 3. TABELA: USUARIO_ROLE
-- Relaciona usuários com suas respectivas roles.
-- Um usuário pode possuir várias roles.
-- ============================================

CREATE TABLE USUARIO_ROLE (
    ID_USUARIO VARCHAR2(36) NOT NULL,
    ID_ROLE NUMBER NOT NULL,

    CONSTRAINT PK_USUARIO_ROLE
        PRIMARY KEY (ID_USUARIO, ID_ROLE),

    CONSTRAINT FK_UR_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_UR_ROLE
        FOREIGN KEY (ID_ROLE)
        REFERENCES ROLE (ID)
);


-- ============================================
-- 4. TABELA: ROTA_SALVA
-- Armazena os trajetos salvos pelos usuários.
-- Cada rota possui uma estação de origem e destino
-- e o critério usado no cálculo (enum CriterioRota).
-- ============================================

CREATE TABLE ROTA_SALVA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    ID_ESTACAO_ORIGEM NUMBER NOT NULL,
    ID_ESTACAO_DESTINO NUMBER NOT NULL,
    CRITERIO VARCHAR2(30) DEFAULT 'EQUILIBRADO' NOT NULL,
    ID_USUARIO VARCHAR2(36) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ROTA_SALVA
        PRIMARY KEY (ID),

    CONSTRAINT FK_RS_ORIGEM
        FOREIGN KEY (ID_ESTACAO_ORIGEM)
        REFERENCES ESTACAO (ID),

    CONSTRAINT FK_RS_DESTINO
        FOREIGN KEY (ID_ESTACAO_DESTINO)
        REFERENCES ESTACAO (ID),

    CONSTRAINT FK_RS_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_RS_ORIGEM_DESTINO
        CHECK (ID_ESTACAO_ORIGEM <> ID_ESTACAO_DESTINO),

    CONSTRAINT CK_RS_CRITERIO
        CHECK (CRITERIO IN ('MENOR_TEMPO', 'MENOS_BALDEACOES', 'EQUILIBRADO'))
);


-- ============================================
-- 5. TABELA: ROTA_AGENDADA
-- Armazena os horários habituais de utilização
-- de cada rota salva pelo usuário.
-- ============================================

CREATE TABLE ROTA_AGENDADA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ROTA_SALVA NUMBER NOT NULL,
    -- Horário de partida em minutos desde a meia-noite (07:10 = 430).
    -- O Oracle não tem tipo TIME; como número, dá para comparar e ordenar direto no SQL.
    HORARIO_PARTIDA_MINUTOS NUMBER(4) NOT NULL,
    ANTECEDENCIA_MINUTOS NUMBER(4) NOT NULL,
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ROTA_AGENDADA
        PRIMARY KEY (ID),

    CONSTRAINT FK_RA_ROTA_SALVA
        FOREIGN KEY (ID_ROTA_SALVA)
        REFERENCES ROTA_SALVA (ID)
        ON DELETE CASCADE,

    -- De 00:00 (0) a 23:59 (1439).
    CONSTRAINT CK_RA_HORARIO
        CHECK (HORARIO_PARTIDA_MINUTOS BETWEEN 0 AND 1439),

    -- Entre 0 e 24 horas de antecedência.
    CONSTRAINT CK_RA_ANTECEDENCIA
        CHECK (ANTECEDENCIA_MINUTOS BETWEEN 0 AND 1440),

    CONSTRAINT CK_RA_ATIVA
        CHECK (ATIVA IN (0, 1))
);


-- ============================================
-- 6. TABELA: AGENDAMENTO_DIA_SEMANA
-- Armazena os dias da semana em que determinado
-- agendamento deve ser executado.
-- ============================================

CREATE TABLE AGENDAMENTO_DIA_SEMANA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ROTA_AGENDADA NUMBER NOT NULL,
    DIA VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_AGENDAMENTO_DIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_ADS_ROTA_AGENDADA
        FOREIGN KEY (ID_ROTA_AGENDADA)
        REFERENCES ROTA_AGENDADA (ID)
        ON DELETE CASCADE,

    -- Também serve de índice para a FK (começa por ID_ROTA_AGENDADA).
    CONSTRAINT UK_ADS_AGENDAMENTO_DIA
        UNIQUE (ID_ROTA_AGENDADA, DIA),

    CONSTRAINT CK_ADS_DIA
        CHECK (
            DIA IN (
                'SEGUNDA',
                'TERCA',
                'QUARTA',
                'QUINTA',
                'SEXTA',
                'SABADO',
                'DOMINGO'
            )
        )
);


-- ============================================
-- ÍNDICES PARA CHAVES ESTRANGEIRAS
-- (FKs cobertas por PK/UK compostas não precisam
-- de índice próprio: USUARIO_ROLE.ID_USUARIO e
-- AGENDAMENTO_DIA_SEMANA.ID_ROTA_AGENDADA.)
-- ============================================

CREATE INDEX IDX_UR_ROLE
    ON USUARIO_ROLE (ID_ROLE);

CREATE INDEX IDX_RS_ORIGEM
    ON ROTA_SALVA (ID_ESTACAO_ORIGEM);

CREATE INDEX IDX_RS_DESTINO
    ON ROTA_SALVA (ID_ESTACAO_DESTINO);

CREATE INDEX IDX_RS_USUARIO
    ON ROTA_SALVA (ID_USUARIO);

CREATE INDEX IDX_RA_ROTA_SALVA
    ON ROTA_AGENDADA (ID_ROTA_SALVA);


