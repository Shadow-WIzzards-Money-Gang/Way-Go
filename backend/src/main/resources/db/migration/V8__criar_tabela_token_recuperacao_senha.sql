-- ============================================
-- TABELA: TOKEN_RECUPERACAO_SENHA
-- Guarda os códigos de recuperação de senha enviados por e-mail.
-- O código (6 dígitos) é armazenado só como hash; vale por 15 minutos,
-- aceita no máximo 5 tentativas e só pode ser usado uma vez (USADO_EM).
-- ============================================

CREATE TABLE TOKEN_RECUPERACAO_SENHA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO VARCHAR2(36) NOT NULL,
    CODIGO_HASH VARCHAR2(255) NOT NULL,
    EXPIRA_EM TIMESTAMP NOT NULL,
    TENTATIVAS NUMBER(2) DEFAULT 0 NOT NULL,
    USADO_EM TIMESTAMP,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_TOKEN_REC_SENHA
        PRIMARY KEY (ID),

    CONSTRAINT FK_TRS_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_TRS_TENTATIVAS
        CHECK (TENTATIVAS >= 0)
);

CREATE INDEX IDX_TRS_USUARIO
    ON TOKEN_RECUPERACAO_SENHA (ID_USUARIO, CRIADO_EM);
