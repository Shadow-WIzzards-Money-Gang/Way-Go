-- ============================================
-- 1. TABELA: DISPOSITIVO_USUARIO
-- Aparelhos que recebem notificações push (FCM).
-- Um token pertence a um só usuário: se outra conta
-- entrar no mesmo aparelho, o token passa para ela.
-- ============================================

CREATE TABLE DISPOSITIVO_USUARIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO VARCHAR2(36) NOT NULL,
    TOKEN_FCM VARCHAR2(512) NOT NULL,
    PLATAFORMA VARCHAR2(10) NOT NULL,
    -- Liga/desliga os alertas de mudança de status das linhas (US15).
    ALERTAS_STATUS NUMBER(1) DEFAULT 1 NOT NULL,
    -- 0 quando o FCM informa que o token não existe mais.
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DISPOSITIVO_USUARIO
        PRIMARY KEY (ID),

    CONSTRAINT FK_DU_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_DU_TOKEN
        UNIQUE (TOKEN_FCM),

    CONSTRAINT CK_DU_PLATAFORMA
        CHECK (PLATAFORMA IN ('ANDROID', 'IOS')),

    CONSTRAINT CK_DU_ALERTAS_STATUS
        CHECK (ALERTAS_STATUS IN (0, 1)),

    CONSTRAINT CK_DU_ATIVO
        CHECK (ATIVO IN (0, 1))
);

CREATE INDEX IDX_DU_USUARIO
    ON DISPOSITIVO_USUARIO (ID_USUARIO);


-- ============================================
-- 2. TABELA: NOTIFICACAO
-- Histórico e fila de envio das notificações push.
-- A chave única (ID_USUARIO, CHAVE) impede que a mesma
-- notificação seja criada duas vezes para o usuário
-- (ex.: "agendamento:12:2026-11-16", "status:345").
-- Enquanto PENDENTE, é reenviada com espera crescente
-- até ser entregue ou passar de EXPIRA_EM.
-- ============================================

CREATE TABLE NOTIFICACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO VARCHAR2(36) NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    CHAVE VARCHAR2(150) NOT NULL,
    TITULO VARCHAR2(150) NOT NULL,
    CORPO VARCHAR2(1000) NOT NULL,
    -- Dados para o app (JSON), ex.: estações da rota para abrir no mapa.
    DADOS VARCHAR2(2000),
    STATUS VARCHAR2(15) DEFAULT 'PENDENTE' NOT NULL,
    TENTATIVAS NUMBER(3) DEFAULT 0 NOT NULL,
    PROXIMA_TENTATIVA_EM TIMESTAMP NOT NULL,
    EXPIRA_EM TIMESTAMP NOT NULL,
    ULTIMO_ERRO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ENVIADA_EM TIMESTAMP,

    CONSTRAINT PK_NOTIFICACAO
        PRIMARY KEY (ID),

    CONSTRAINT FK_NOT_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID)
        ON DELETE CASCADE,

    -- Também serve de índice para a FK (começa por ID_USUARIO).
    CONSTRAINT UK_NOT_USUARIO_CHAVE
        UNIQUE (ID_USUARIO, CHAVE),

    CONSTRAINT CK_NOT_TIPO
        CHECK (TIPO IN ('LEMBRETE_AGENDAMENTO', 'STATUS_LINHA')),

    CONSTRAINT CK_NOT_STATUS
        CHECK (STATUS IN ('PENDENTE', 'ENVIADA', 'EXPIRADA')),

    CONSTRAINT CK_NOT_TENTATIVAS
        CHECK (TENTATIVAS >= 0)
);

-- Busca da fila: pendentes cuja próxima tentativa já chegou.
CREATE INDEX IDX_NOT_FILA
    ON NOTIFICACAO (STATUS, PROXIMA_TENTATIVA_EM);
