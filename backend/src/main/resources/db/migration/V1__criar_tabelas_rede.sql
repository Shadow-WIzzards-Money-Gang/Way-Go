-- ============================================
-- 1. TABELA: LINHA_TRANSPORTE
-- Armazena as linhas de metrô e trem.
-- ============================================

CREATE TABLE LINHA_TRANSPORTE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    CODIGO VARCHAR2(20) NOT NULL,
    COR VARCHAR2(20),
    OPERADORA VARCHAR2(100) NOT NULL,
    TIPO_TRANSPORTE VARCHAR2(30) NOT NULL,
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_LINHA_TRANSPORTE
        PRIMARY KEY (ID),

    CONSTRAINT UK_LINHA_CODIGO
        UNIQUE (CODIGO),

    CONSTRAINT CK_LINHA_ATIVA
        CHECK (ATIVA IN (0, 1))
);


-- ============================================
-- 2. TABELA: ESTACAO
-- Armazena as estações físicas.
-- ============================================

CREATE TABLE ESTACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(150) NOT NULL,
    LATITUDE NUMBER(10, 7),
    LONGITUDE NUMBER(10, 7),
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_ESTACAO
        PRIMARY KEY (ID),

    CONSTRAINT CK_ESTACAO_ATIVA
        CHECK (ATIVA IN (0, 1)),

    CONSTRAINT CK_ESTACAO_LATITUDE
        CHECK (LATITUDE BETWEEN -90 AND 90),

    CONSTRAINT CK_ESTACAO_LONGITUDE
        CHECK (LONGITUDE BETWEEN -180 AND 180)
);


-- ============================================
-- 3. TABELA: LINHA_ESTACAO
-- Relaciona linhas com estações.
-- Armazena a ordem da estação na linha.
-- ============================================

CREATE TABLE LINHA_ESTACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LINHA NUMBER NOT NULL,
    ID_ESTACAO NUMBER NOT NULL,
    SEQUENCIA NUMBER(5) NOT NULL,
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_LINHA_ESTACAO
        PRIMARY KEY (ID),

    CONSTRAINT FK_LE_LINHA
        FOREIGN KEY (ID_LINHA)
        REFERENCES LINHA_TRANSPORTE (ID),

    CONSTRAINT FK_LE_ESTACAO
        FOREIGN KEY (ID_ESTACAO)
        REFERENCES ESTACAO (ID),

    CONSTRAINT UK_LE_LINHA_ESTACAO
        UNIQUE (ID_LINHA, ID_ESTACAO),

    CONSTRAINT UK_LE_SEQUENCIA
        UNIQUE (ID_LINHA, SEQUENCIA),

    CONSTRAINT CK_LE_SEQUENCIA
        CHECK (SEQUENCIA > 0),

    CONSTRAINT CK_LE_ATIVA
        CHECK (ATIVA IN (0, 1))
);


-- ============================================
-- 4. TABELA: CONEXAO_ESTACAO
-- Registra conexões entre estações consecutivas
-- de uma linha.
-- ============================================

CREATE TABLE CONEXAO_ESTACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LINHA_ESTACAO_ORIGEM NUMBER NOT NULL,
    ID_LINHA_ESTACAO_DESTINO NUMBER NOT NULL,
    TEMPO_VIAGEM_SEGUNDOS NUMBER(8),
    DISTANCIA_METROS NUMBER(10),
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_CONEXAO_ESTACAO
        PRIMARY KEY (ID),

    CONSTRAINT FK_CE_ORIGEM
        FOREIGN KEY (ID_LINHA_ESTACAO_ORIGEM)
        REFERENCES LINHA_ESTACAO (ID),

    CONSTRAINT FK_CE_DESTINO
        FOREIGN KEY (ID_LINHA_ESTACAO_DESTINO)
        REFERENCES LINHA_ESTACAO (ID),

    CONSTRAINT UK_CE_CONEXAO
        UNIQUE (
            ID_LINHA_ESTACAO_ORIGEM,
            ID_LINHA_ESTACAO_DESTINO
        ),

    CONSTRAINT CK_CE_ORIGEM_DESTINO
        CHECK (
            ID_LINHA_ESTACAO_ORIGEM <>
            ID_LINHA_ESTACAO_DESTINO
        ),

    CONSTRAINT CK_CE_TEMPO
        CHECK (TEMPO_VIAGEM_SEGUNDOS > 0),

    CONSTRAINT CK_CE_DISTANCIA
        CHECK (DISTANCIA_METROS > 0),

    CONSTRAINT CK_CE_ATIVA
        CHECK (ATIVA IN (0, 1))
);


-- ============================================
-- 5. TABELA: BALDEACAO
-- Registra as conexões entre linhas diferentes
-- em estações integradas.
-- ============================================

CREATE TABLE BALDEACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LINHA_ESTACAO_ORIGEM NUMBER NOT NULL,
    ID_LINHA_ESTACAO_DESTINO NUMBER NOT NULL,
    TEMPO_BALDEACAO_SEGUNDOS NUMBER(8),
    ATIVA NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_BALDEACAO
        PRIMARY KEY (ID),

    CONSTRAINT FK_BAL_ORIGEM
        FOREIGN KEY (ID_LINHA_ESTACAO_ORIGEM)
        REFERENCES LINHA_ESTACAO (ID),

    CONSTRAINT FK_BAL_DESTINO
        FOREIGN KEY (ID_LINHA_ESTACAO_DESTINO)
        REFERENCES LINHA_ESTACAO (ID),

    CONSTRAINT UK_BAL_CONEXAO
        UNIQUE (
            ID_LINHA_ESTACAO_ORIGEM,
            ID_LINHA_ESTACAO_DESTINO
        ),

    CONSTRAINT CK_BAL_ORIGEM_DESTINO
        CHECK (
            ID_LINHA_ESTACAO_ORIGEM <>
            ID_LINHA_ESTACAO_DESTINO
        ),

    CONSTRAINT CK_BAL_TEMPO
        CHECK (TEMPO_BALDEACAO_SEGUNDOS > 0),

    CONSTRAINT CK_BAL_ATIVA
        CHECK (ATIVA IN (0, 1))
);


-- ============================================
-- ÍNDICES PARA CHAVES ESTRANGEIRAS
-- ============================================

CREATE INDEX IDX_LE_ESTACAO
    ON LINHA_ESTACAO (ID_ESTACAO);

CREATE INDEX IDX_CE_ORIGEM
    ON CONEXAO_ESTACAO (ID_LINHA_ESTACAO_ORIGEM);

CREATE INDEX IDX_CE_DESTINO
    ON CONEXAO_ESTACAO (ID_LINHA_ESTACAO_DESTINO);

CREATE INDEX IDX_BAL_ORIGEM
    ON BALDEACAO (ID_LINHA_ESTACAO_ORIGEM);

CREATE INDEX IDX_BAL_DESTINO
    ON BALDEACAO (ID_LINHA_ESTACAO_DESTINO);
